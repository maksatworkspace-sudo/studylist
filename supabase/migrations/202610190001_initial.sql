CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC;

CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY, name text NOT NULL, email text NOT NULL UNIQUE,
  phone text NOT NULL, role text NOT NULL DEFAULT 'user' CHECK (role IN ('user','teacher','admin','leadership')),
  verified boolean NOT NULL DEFAULT false, active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS courses (id uuid PRIMARY KEY, name text NOT NULL UNIQUE, active boolean NOT NULL DEFAULT true);
CREATE TABLE IF NOT EXISTS teachers (
  id uuid PRIMARY KEY, profile_id uuid UNIQUE REFERENCES profiles(id), name text NOT NULL,
  subject text NOT NULL, color text NOT NULL DEFAULT 'blue', active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS feedback (
  id uuid PRIMARY KEY, number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE,
  type text NOT NULL CHECK (type IN ('opinion','suggestion','issue')),
  title text NOT NULL CHECK (char_length(title) BETWEEN 3 AND 160), body text NOT NULL CHECK (char_length(body) BETWEEN 10 AND 10000),
  course_id uuid REFERENCES courses(id), teacher_id uuid REFERENCES teachers(id), custom_target text,
  anonymous boolean NOT NULL DEFAULT false, author_name text,
  status text CHECK (status IN ('new','reviewing','resolved','in_progress','reviewed')),
  outcome text CHECK (outcome IN ('implemented','declined')), confirmed boolean NOT NULL DEFAULT false,
  hidden boolean NOT NULL DEFAULT false, hidden_reason text, deleted boolean NOT NULL DEFAULT false,
  resolved_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((anonymous AND author_name IS NULL) OR (NOT anonymous AND author_name IS NOT NULL)),
  CHECK ((type='issue' AND status IN ('new','reviewing','resolved') AND outcome IS NULL)
    OR (type='suggestion' AND ((status='in_progress' AND outcome IS NULL) OR (status='reviewed' AND outcome IS NOT NULL)))
    OR (type='opinion' AND status IS NULL AND outcome IS NULL))
);
CREATE TABLE IF NOT EXISTS private.feedback_access (
  feedback_id uuid PRIMARY KEY REFERENCES feedback(id) ON DELETE CASCADE,
  profile_id uuid REFERENCES profiles(id), recovery_email text, code_hash text
);
CREATE TABLE IF NOT EXISTS private.sessions (
  token_hash text PRIMARY KEY, profile_id uuid REFERENCES profiles(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL, provider_session text
);
CREATE TABLE IF NOT EXISTS private.guest_grants (
  token_hash text REFERENCES private.sessions(token_hash) ON DELETE CASCADE,
  feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE, expires_at timestamptz NOT NULL,
  PRIMARY KEY (token_hash, feedback_id)
);
CREATE TABLE IF NOT EXISTS private.local_credentials (
  profile_id uuid PRIMARY KEY REFERENCES profiles(id) ON DELETE CASCADE, password_hash text NOT NULL
);
CREATE TABLE IF NOT EXISTS private.tokens (
  token_hash text PRIMARY KEY, purpose text NOT NULL, subject_id uuid NOT NULL, expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS official_replies (
  id uuid PRIMARY KEY, feedback_id uuid NOT NULL REFERENCES feedback(id) ON DELETE CASCADE,
  profile_id uuid NOT NULL REFERENCES profiles(id), body text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS comments (
  id uuid PRIMARY KEY, feedback_id uuid NOT NULL REFERENCES feedback(id) ON DELETE CASCADE,
  profile_id uuid NOT NULL REFERENCES profiles(id), parent_id uuid REFERENCES comments(id),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 5000), deleted boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS supports (
  profile_id uuid REFERENCES profiles(id) ON DELETE CASCADE, feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE,
  PRIMARY KEY(profile_id,feedback_id)
);
CREATE TABLE IF NOT EXISTS bookmarks (
  profile_id uuid REFERENCES profiles(id) ON DELETE CASCADE, feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE,
  PRIMARY KEY(profile_id,feedback_id)
);
CREATE TABLE IF NOT EXISTS ratings (
  profile_id uuid REFERENCES profiles(id) ON DELETE CASCADE, teacher_id uuid REFERENCES teachers(id) ON DELETE CASCADE,
  stars smallint NOT NULL CHECK (stars BETWEEN 1 AND 5), comment text NOT NULL DEFAULT '' CHECK (char_length(comment)<=3000),
  updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(profile_id,teacher_id)
);
CREATE TABLE IF NOT EXISTS status_history (
  id uuid PRIMARY KEY, feedback_id uuid NOT NULL REFERENCES feedback(id) ON DELETE CASCADE,
  status text NOT NULL, outcome text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS private.notifications (
  id uuid PRIMARY KEY, profile_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE, title text NOT NULL, read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS private.attachments (
  id uuid PRIMARY KEY, feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE,
  token_hash text REFERENCES private.sessions(token_hash) ON DELETE SET NULL, name text NOT NULL, mime text NOT NULL,
  size bigint NOT NULL CHECK(size>=0 AND size<=20971520), object_path text NOT NULL UNIQUE,
  ready boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS private.jobs (
  id uuid PRIMARY KEY, kind text NOT NULL, subject_id uuid, payload text NOT NULL DEFAULT '{}',
  status text NOT NULL DEFAULT 'pending', attempts integer NOT NULL DEFAULT 0,
  available_at timestamptz NOT NULL DEFAULT now(), last_error text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS private.moderation_flags (
  id uuid PRIMARY KEY, feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE,
  reason text NOT NULL, source text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS private.rate_limits (key text PRIMARY KEY, count integer NOT NULL, resets_at timestamptz NOT NULL);
CREATE TABLE IF NOT EXISTS private.submissions (key text PRIMARY KEY, feedback_id uuid REFERENCES feedback(id) ON DELETE CASCADE);

CREATE INDEX IF NOT EXISTS feedback_feed ON feedback(created_at DESC) WHERE NOT deleted;
CREATE INDEX IF NOT EXISTS feedback_filters ON feedback(type,status,course_id,teacher_id);
CREATE INDEX IF NOT EXISTS comments_feedback ON comments(feedback_id,created_at);
ALTER TABLE comments DROP CONSTRAINT IF EXISTS comments_body_check;
ALTER TABLE comments ADD CONSTRAINT comments_body_check CHECK ((deleted OR char_length(body)>=1) AND char_length(body)<=5000);
ALTER TABLE private.attachments ALTER COLUMN token_hash DROP NOT NULL;
ALTER TABLE private.attachments DROP CONSTRAINT IF EXISTS attachments_token_hash_fkey;
ALTER TABLE private.attachments ADD CONSTRAINT attachments_token_hash_fkey FOREIGN KEY(token_hash) REFERENCES private.sessions(token_hash) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS jobs_pending ON private.jobs(status,available_at);
CREATE INDEX IF NOT EXISTS sessions_expiry ON private.sessions(expires_at);

